CREATE TABLE shop_settings (
    id bigint PRIMARY KEY CHECK (id = 1),
    name varchar(100) NOT NULL CHECK (btrim(name) <> ''),
    phone varchar(30), telegram varchar(200), address varchar(250), directions varchar(1000),
    map_url varchar(1000), hours varchar(200), version bigint NOT NULL DEFAULT 0
);

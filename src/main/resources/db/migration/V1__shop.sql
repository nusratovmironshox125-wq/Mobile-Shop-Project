CREATE TABLE product (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id bigint NOT NULL REFERENCES category,
    brand varchar(100) NOT NULL, name varchar(150) NOT NULL, slug varchar(150) NOT NULL UNIQUE,
    description varchar(5000) NOT NULL DEFAULT '',
    status varchar(12) NOT NULL CHECK (status IN ('DRAFT','PUBLISHED','ARCHIVED')),
    created_at timestamptz NOT NULL DEFAULT now(), version bigint NOT NULL DEFAULT 0
);
CREATE INDEX product_category_public_idx ON product (category_id, id) WHERE status = 'PUBLISHED';

CREATE TABLE product_variant (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES product ON DELETE CASCADE,
    sku varchar(80) NOT NULL UNIQUE, color varchar(100), ram_gb integer CHECK (ram_gb > 0),
    storage_gb integer CHECK (storage_gb > 0), screen varchar(100), cpu varchar(100), gpu varchar(100),
    cameras varchar(150), battery varchar(100), sim varchar(100), os varchar(100), weight varchar(100),
    notes varchar(1000),
    price numeric(16,2) NOT NULL CHECK (price > 0),
    stock varchar(16) NOT NULL CHECK (stock IN ('IN_STOCK','OUT_OF_STOCK')),
    installment boolean NOT NULL DEFAULT false, installment_terms varchar(1000),
    sale_price numeric(16,2), sale_from timestamptz, sale_until timestamptz,
    CHECK (sale_price IS NULL OR (sale_price > 0 AND sale_price < price)),
    CHECK (sale_from IS NULL OR sale_until IS NULL OR sale_from < sale_until),
    CHECK (sale_price IS NOT NULL OR (sale_from IS NULL AND sale_until IS NULL)),
    version bigint NOT NULL DEFAULT 0
);
CREATE INDEX product_variant_product_idx ON product_variant (product_id, id);

CREATE TABLE product_image (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES product ON DELETE CASCADE,
    variant_id bigint REFERENCES product_variant ON DELETE CASCADE,
    storage_key uuid NOT NULL UNIQUE, width integer NOT NULL CHECK (width > 0),
    height integer NOT NULL CHECK (height > 0), alt varchar(200)
);
CREATE INDEX product_image_product_idx ON product_image (product_id, id);

CREATE TABLE admin_user (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login varchar(60) NOT NULL UNIQUE, name varchar(100) NOT NULL, password_hash varchar(255) NOT NULL,
    role varchar(8) NOT NULL CHECK (role IN ('OWNER','ADMIN')),
    enabled boolean NOT NULL DEFAULT true, must_change boolean NOT NULL DEFAULT false,
    auth_version bigint NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(), last_login timestamptz,
    version bigint NOT NULL DEFAULT 0
);

CREATE TABLE lead (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_number uuid NOT NULL UNIQUE, idempotency_key uuid NOT NULL UNIQUE, request_hash varchar(64) NOT NULL,
    name varchar(80), phone varchar(20), product_id bigint NOT NULL REFERENCES product,
    variant_id bigint NOT NULL REFERENCES product_variant, product_name varchar(255) NOT NULL,
    sku varchar(80) NOT NULL, variant_label varchar(400) NOT NULL, price numeric(16,2) NOT NULL CHECK (price > 0),
    original_price numeric(16,2), installment boolean NOT NULL, installment_terms varchar(1000),
    currency char(3) NOT NULL DEFAULT 'UZS' CHECK (currency = 'UZS'),
    status varchar(12) NOT NULL CHECK (status IN ('NEW','CONTACTED','COMPLETED','CANCELLED')),
    comment varchar(2000), privacy_version varchar(80) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(), closed_at timestamptz, anonymized_at timestamptz,
    version bigint NOT NULL DEFAULT 0
);
CREATE INDEX lead_created_idx ON lead (created_at DESC, id DESC);
CREATE INDEX lead_status_idx ON lead (status, created_at DESC, id DESC);
CREATE INDEX lead_phone_idx ON lead (phone, created_at DESC);
CREATE INDEX lead_sku_idx ON lead (sku);
CREATE INDEX lead_variant_idx ON lead (variant_id);

CREATE TABLE lead_status_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id bigint NOT NULL REFERENCES lead,
    actor_id bigint NOT NULL REFERENCES admin_user, previous_status varchar(12) NOT NULL,
    new_status varchar(12) NOT NULL, reason varchar(2000),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX lead_history_idx ON lead_status_history (lead_id, id);

CREATE TABLE notification_outbox (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id bigint NOT NULL UNIQUE REFERENCES lead,
    status varchar(12) NOT NULL CHECK (status IN ('PENDING','SENT','FAILED','CANCELLED')),
    attempts integer NOT NULL DEFAULT 0,
    next_attempt timestamptz NOT NULL DEFAULT now(), lease_until timestamptz, lease_token uuid,
    last_error varchar(50)
);
CREATE INDEX outbox_pending_idx ON notification_outbox (next_attempt, id) WHERE status = 'PENDING';

CREATE TABLE audit_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id bigint REFERENCES admin_user, action varchar(80) NOT NULL,
    target varchar(120), correlation_id uuid NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX audit_created_idx ON audit_event (created_at DESC, id DESC);
